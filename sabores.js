// Normaliza texto: minúsculas, sem acento, sem espaços sobrando
function normalizarTexto(t) {
  return String(t)
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

// Mapa apelido -> nome oficial (montado uma vez). Nomes oficiais têm prioridade.
const MAPA_SABORES = new Map();
SABORES.forEach(s => MAPA_SABORES.set(normalizarTexto(s.nome), s.nome));
SABORES.forEach(s => {
  s.aliases.forEach(a => {
    const chave = normalizarTexto(a);
    if (!MAPA_SABORES.has(chave)) MAPA_SABORES.set(chave, s.nome);
  });
});

function encontrarNomeOficial(nomeDigitado) {
  return MAPA_SABORES.get(normalizarTexto(nomeDigitado)) || nomeDigitado;
}

function escaparHtml(t) {
  return String(t).replace(/[&<>"']/g, c => ({
    '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;'
  }[c]));
}

